/* 語言偵測:瀏覽器語言 → 三語之一 */
window.I18N.detect = function () {
  var saved = null;
  try { saved = localStorage.getItem("site-lang"); } catch (e) { /* ignore */ }
  if (saved && window.I18N[saved]) return saved;
  var nav = (navigator.language || "zh-Hant").toLowerCase();
  if (nav.indexOf("zh") === 0) {
    // 含 hant/tw/hk/mo → 繁體;其餘中文 → 簡體
    if (/hant|tw|hk|mo/.test(nav)) return "zh-Hant";
    return "zh-Hans";
  }
  return "en";
};

/* 套用語言:重寫所有 data-i18n 元素 + 更新標題/按鈕/記憶 */
window.I18N.apply = function (lang) {
  var dict = window.I18N[lang];
  document.documentElement.lang = lang;
  document.documentElement.setAttribute("data-lang", lang);

  var els = document.querySelectorAll("[data-i18n]");
  for (var i = 0; i < els.length; i++) {
    var el = els[i];
    var key = el.getAttribute("data-i18n");
    if (dict[key]) {
      if (el.tagName === "TITLE") document.title = dict[key];
      else el.textContent = dict[key].replace("__YEAR__", String(new Date().getFullYear()));
    }
  }

  var btns = document.querySelectorAll(".lang-btn");
  for (var j = 0; j < btns.length; j++) {
    btns[j].setAttribute("aria-pressed", String(btns[j].getAttribute("data-lang") === lang));
  }

  try { localStorage.setItem("site-lang", lang); } catch (e) { /* ignore */ }
};
